-- 基礎講座文字起こしの突き合わせ（自分用 jarvis-dashboard）
-- チャットボット正本は kamiooya-qa の knowledge_*（今村 canonical）側。
-- 本テーブルは Jarvis VTT vs 今村字幕の比較・確認ログ用。

create table if not exists public.westudy_transcript_compare (
  id bigint primary key generated by default as identity,
  lesson_slug text not null,
  lesson_title text,
  jarvis_status text not null default 'missing'
    check (jarvis_status in ('missing','ready','error','skipped')),
  imamura_status text not null default 'missing'
    check (imamura_status in ('missing','inbox','canonical','ingested')),
  jarvis_path text,
  imamura_path text,
  cue_count_jarvis integer,
  cue_count_imamura integer,
  diff_notes text,
  decision text not null default 'pending'
    check (decision in ('pending','use_imamura','use_jarvis','merge','skip')),
  jarvis_understood_summary text,
  meta_json jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  unique (lesson_slug)
);

create index if not exists westudy_transcript_compare_decision_idx
  on public.westudy_transcript_compare (decision);
create index if not exists westudy_transcript_compare_updated_idx
  on public.westudy_transcript_compare (updated_at desc);

alter table public.westudy_transcript_compare enable row level security;

revoke all on table public.westudy_transcript_compare from anon, authenticated;
grant select, insert, update, delete on table public.westudy_transcript_compare to service_role;
grant usage, select on sequence public.westudy_transcript_compare_id_seq to service_role;
