-- Quiet Edge Phase 1: snore + treatment tables + seed

create table if not exists public.vital_snore_daily (
  recorded_at date primary key,
  score double precision not null,
  count integer,
  event text not null default '通常日',
  sleep_time text,
  memo text,
  source text not null default 'autosnore_ocr',
  payload jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index if not exists vital_snore_daily_recorded_idx
  on public.vital_snore_daily (recorded_at desc);

create table if not exists public.vital_treatment_events (
  id bigint generated by default as identity primary key,
  session_no integer not null unique,
  scheduled_at timestamptz not null,
  label text not null,
  status text not null default 'scheduled'
    check (status in ('done', 'scheduled', 'cancelled')),
  note text,
  payload jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index if not exists vital_treatment_events_scheduled_idx
  on public.vital_treatment_events (scheduled_at);

alter table public.vital_snore_daily enable row level security;
alter table public.vital_treatment_events enable row level security;

drop policy if exists vital_snore_daily_auth_all on public.vital_snore_daily;
create policy vital_snore_daily_auth_all on public.vital_snore_daily
  for all to authenticated
  using (true)
  with check (true);

drop policy if exists vital_treatment_events_auth_all on public.vital_treatment_events;
create policy vital_treatment_events_auth_all on public.vital_treatment_events
  for all to authenticated
  using (true)
  with check (true);

