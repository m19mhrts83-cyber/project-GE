-- KURASHIFT HQ: liquidity history, securities holdings, money ops
-- Project: jarvis-dashboard

create table if not exists public.liquidity_accounts (
  id text primary key,
  name text not null,
  kind text not null
    check (kind in ('bank', 'card', 'emoney', 'cash')),
  zaim_match text not null,
  active boolean not null default true,
  sort_order int not null default 100,
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.liquidity_snapshots (
  id bigint generated by default as identity primary key,
  account_id text not null references public.liquidity_accounts(id) on delete cascade,
  as_of date not null,
  balance_jpy numeric not null,
  source text not null default 'zaim',
  note text,
  created_at timestamptz not null default now(),
  unique (account_id, as_of)
);

create index if not exists liquidity_snapshots_as_of_idx
  on public.liquidity_snapshots (as_of desc);

create table if not exists public.cashflow_week_summaries (
  week_start date primary key,
  income_jpy numeric,
  expense_jpy numeric,
  credit_spend_jpy numeric,
  note text,
  source text not null default 'zaim',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.securities_holdings (
  id bigint generated by default as identity primary key,
  account_id text not null references public.portfolio_accounts(id) on delete cascade,
  as_of date not null,
  value_jpy numeric,
  source text,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (account_id, as_of)
);

create index if not exists securities_holdings_as_of_idx
  on public.securities_holdings (as_of desc);

-- kind は後続で card_settlement_buffer を追加
-- （20260814_kurashift_money_ops_card_settlement.sql）
create table if not exists public.kurashift_money_ops (
  id uuid primary key default gen_random_uuid(),
  kind text not null
    check (kind in (
      'bank_transfer', 'broker_transfer', 'securities_cash', 'insurance_alloc',
      'card_settlement_buffer'
    )),
  title text not null,
  rationale text not null default '',
  from_account text,
  to_account text,
  amount_jpy numeric,
  status text not null default 'draft'
    check (status in ('draft', 'consulting', 'approved', 'executing', 'done', 'cancelled')),
  assist_payload jsonb not null default '{}'::jsonb,
  consultation_id uuid references public.kurashift_consultations(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists kurashift_money_ops_status_created_idx
  on public.kurashift_money_ops (status, created_at desc);

