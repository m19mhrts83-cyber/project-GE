declare
  t text;
begin
  foreach t in array array[
    'liquidity_accounts', 'liquidity_snapshots', 'cashflow_week_summaries',
    'securities_holdings', 'kurashift_money_ops'
  ]
  loop
    execute format('alter table public.%I enable row level security', t);
